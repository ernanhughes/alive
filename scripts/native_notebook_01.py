def squash(text):
    return " ".join(text.split())


async def wait_url(url, seconds=60):
    started = asyncio.get_running_loop().time()
    async with httpx.AsyncClient(timeout=2) as client:
        while asyncio.get_running_loop().time() - started < seconds:
            try:
                if (await client.get(url)).status_code == 200:
                    return
            except httpx.HTTPError:
                pass
            await asyncio.sleep(0.25)
    raise TimeoutError("Hugo did not become ready at " + url)


def start_hugo(log_path):
    log = open(log_path, "a", encoding="utf-8")
    process = subprocess.Popen(
        [
            "hugo",
            "server",
            "--source",
            str(SITE),
            "--bind",
            "127.0.0.1",
            "--port",
            str(SPEC["port"]),
            "--disableLiveReload",
            "--quiet",
        ],
        cwd=ROOT,
        stdout=log,
        stderr=subprocess.STDOUT,
    )
    return process, log


async def api_json(backend, token, method, path, body=None):
    headers = {"Authorization": "Bearer " + token, "Content-Type": "application/json"}
    async with httpx.AsyncClient(timeout=30) as client:
        response = await client.request(
            method, backend + "/api/v1/browser-experience" + path, json=body, headers=headers
        )
        response.raise_for_status()
        return response.json()


async def click_label(panel, label):
    await panel.evaluate(
        "(() => { const b=Array.from(document.querySelectorAll('#live-content button'))"
        f".find(b=>b.textContent==={json.dumps(label)}); "
        "if(!b) throw new Error('Missing action'); b.click(); })()"
    )


async def select_quote(page, quote):
    await page.evaluate(
        """quote => {
      const root = document.querySelector('main');
      if (!root) throw new Error('No main content');
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
      let text = '', points = [], node;
      while ((node = walker.nextNode())) {
        for (let i = 0; i < node.nodeValue.length; i++) {
          let char = node.nodeValue[i];
          if (/[\\t\\r\\n\\f\\v ]/.test(char)) char = ' ';
          if (char === ' ' && (!text || text.endsWith(' '))) continue;
          text += char; points.push({node, offset: i});
        }
      }
      const start = text.indexOf(quote);
      if (start < 0) throw new Error('Quote is not visible in main content');
      const first = points[start], last = points[start + quote.length - 1];
      const range = document.createRange();
      range.setStart(first.node, first.offset);
      range.setEnd(last.node, last.offset + 1);
      const selection = window.getSelection();
      selection.removeAllRanges(); selection.addRange(range);
    }""",
        quote,
    )


async def save_panel_png(panel, name):
    await panel.send(
        "Emulation.setDeviceMetricsOverride",
        {"width": 360, "height": 1100, "deviceScaleFactor": 1, "mobile": False},
    )
    assert await panel.evaluate("document.documentElement.scrollWidth <= 360"), "Panel overflow"
    await panel.send("Page.enable")
    result = await panel.send("Page.captureScreenshot", {"captureBeyondViewport": True})
    (EVIDENCE / (name + ".png")).write_bytes(base64.b64decode(result["data"]))


def grant_status(database, grant_id):
    with sqlite3.connect(database) as connection:
        row = connection.execute(
            "select status from web_experiences where id=?", (grant_id,)
        ).fetchone()
    return row[0] if row else None


def latest_connection(database):
    with sqlite3.connect(database) as connection:
        row = connection.execute(
            "select data from web_experiences where kind='research_connection' "
            "order by created_at desc limit 1"
        ).fetchone()
    assert row, "no research connection was stored"
    return json.loads(row[0])


async def main():
    EVIDENCE.mkdir(parents=True, exist_ok=True)
    work = ROOT / ".alive" / ("notebook-native-" + uuid.uuid4().hex)
    work.mkdir(parents=True, exist_ok=True)
    hugo, hugo_log = start_hugo(work / "hugo.log")
    port = chrome_harness.free_port()
    backend = f"http://127.0.0.1:{port}"
    env, token = environment(work, port)
    env["ALIVE_NATIVE_TEST_PAGES"] = ",".join(URLS.values())
    await prepare_schema(env["DATABASE_URL"])
    chrome_harness.TOKEN = token
    process, log = chrome_harness.start_backend(work, env, port)
    report = {
        "source_commit": subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True
        ).strip(),
        "source_status_before_run": subprocess.check_output(
            ["git", "status", "--porcelain"], cwd=ROOT, text=True
        ).strip(),
        "platform": platform.platform(),
        "hugo": subprocess.check_output(["hugo", "version"], text=True).strip(),
        "goal": GOAL,
        "chapters": CHAPTERS,
        "allowlist": sorted(URLS.values()),
        "external_model_calls": 0,
        "paid_inference_spend_usd": 0,
        "steps": [],
    }
    try:
        await wait_url(URLS["alive-12-status"])
        await chrome_harness.wait_backend(backend)
        extension = work / "extension"
        shutil.copytree(ROOT / "extension", extension)
        (extension / "config.js").write_text(
            "export const DEFAULT_BACKEND = " + json.dumps(backend) + ";\n"
            "export const DEFAULT_BACKENDS = [" + json.dumps(backend) + "];\n"
            "export const AUTHORISED_PAGES = " + json.dumps(list(URLS.values())) + ";\n"
            "export function isLocalDemo() { return false; }\n",
            encoding="utf-8",
        )
        copied_manifest = json.loads((extension / "manifest.json").read_text(encoding="utf-8"))
        shipped_permissions = copied_manifest["permissions"]
        # Harness-only loopback permission. CDP Extensions.triggerAction opens the panel
        # but does not grant activeTab, so the test copy must be able to read the tab URL.
        # The shipped manifest is untouched and a real toolbar click grants activeTab.
        copied_manifest["host_permissions"] = [
            backend + "/*",
            f"http://127.0.0.1:{SPEC['port']}/*",
        ]
        (extension / "manifest.json").write_text(
            json.dumps(copied_manifest, indent=2) + "\n", encoding="utf-8"
        )
        report["shipped_permissions"] = shipped_permissions
        report["harness_host_permissions"] = copied_manifest["host_permissions"]

        async with async_playwright() as playwright:
            context = await playwright.chromium.launch_persistent_context(
                str(work / "chrome-profile"),
                channel="chrome",
                headless=False,
                ignore_default_args=["--disable-extensions"],
                args=["--enable-unsafe-extension-debugging", "--window-size=1440,1100"],
            )
            try:
                cdp = await context.browser.new_browser_cdp_session()
                report["chrome"] = await cdp.send("Browser.getVersion")
                extension_id = (
                    await cdp.send("Extensions.loadUnpacked", {"path": str(extension.resolve())})
                )["id"]
                page = await context.new_page()
                await page.goto(URLS["alive-12-status"])
                panel, report["panel"] = await chrome_harness.open_panel(
                    context, cdp, extension_id, page, require_docked=True
                )
                await chrome_harness.connect_panel(panel, backend)
                await panel.evaluate("document.querySelector('#legacy-tools').open = true")

                await panel.evaluate("document.querySelector('#goal').value=" + json.dumps(GOAL))
                await panel.click("#save-goal")
                await panel.wait(
                    "document.querySelector('#status').textContent.includes('Goal saved')"
                )
                goal_id = await panel.evaluate("(await chrome.storage.local.get('goalId')).goalId")
                report["goal_id"] = goal_id

                async def authorise(chapter):
                    url = URLS[chapter]
                    if page.url != url:
                        await page.goto(url, wait_until="domcontentloaded")
                    await page.bring_to_front()
                    await panel.wait(
                        "document.querySelector('#live-companion')"
                        ".getAttribute('aria-busy') !== 'true'"
                    )
                    await panel.evaluate("document.querySelector('#legacy-tools').open = true")
                    await panel.click("#live-authorise")
                    try:
                        await panel.wait(
                            "(await chrome.storage.session.get('latest')).latest?.payload.url === "
                            + json.dumps(url)
                        )
                    except AssertionError:
                        print(
                            json.dumps(
                                {
                                    "diagnostic": "capture did not arrive",
                                    "page_url": page.url,
                                    "live_error": await panel.evaluate(
                                        "document.querySelector('#live-error').textContent"
                                    ),
                                    "live_state": await panel.evaluate(
                                        "document.querySelector('#live-state').textContent"
                                    ),
                                    "status": await panel.evaluate(
                                        "document.querySelector('#status').textContent"
                                    ),
                                    "session": await panel.evaluate(
                                        "await chrome.storage.session.get(null)"
                                    ),
                                    "tabs": await panel.evaluate(
                                        "(await chrome.tabs.query({})).map(t => "
                                        "({id:t.id,url:t.url,active:t.active}))"
                                    ),
                                },
                                indent=2,
                            ),
                            flush=True,
                        )
                        raise
                    await panel.wait(
                        "document.querySelector('#live-companion')"
                        ".getAttribute('aria-busy') !== 'true'"
                    )
                    await panel.wait(
                        "(await chrome.storage.session.get('selected')).selected?.snapshot?.id"
                    )
                    return await panel.evaluate(
                        "(await chrome.storage.session.get('latest')).latest.payload.text"
                    )

                async def remember(chapter):
                    await authorise(chapter)
                    await select_quote(page, QUOTES[chapter])
                    await panel.click("#live-remember")
                    await panel.wait(
                        "document.querySelector('#live-content')"
                        ".textContent.includes('Confirm passage')"
                    )
                    shown = await panel.evaluate(
                        "document.querySelector('#live-content blockquote').textContent"
                    )
                    assert squash(shown) == squash(QUOTES[chapter]), (shown, QUOTES[chapter])
                    await click_label(panel, "Confirm passage")
                    await panel.wait(
                        "document.querySelector('#live-content')"
                        ".textContent.includes('Withdraw saved source')"
                    )
                    memories = (
                        await api_json(
                            backend, token, "GET", "/research/memories?goal_id=" + goal_id
                        )
                    )["memories"]
                    memory = next(row for row in memories if row["data"]["url"] == URLS[chapter])
                    report["steps"].append(
                        {
                            "step": "saved memory",
                            "chapter": chapter,
                            "url": memory["data"]["url"],
                            "sha256": memory["data"]["sha256"],
                            "anchor": memory["data"]["reliance_anchor"]["quote"],
                        }
                    )
                    return memory

                async def find(chapter):
                    await authorise(chapter)
                    await panel.evaluate("document.querySelector('#legacy-tools').open = true")
                    await panel.wait("!document.querySelector('#find-research').disabled")
                    await panel.click("#find-research")
                    await panel.wait(
                        "document.querySelector('#research-results').children.length > 0 || "
                        "document.querySelector('#research-status').textContent"
                        ".includes('No related')"
                    )
                    snapshot_id = await panel.evaluate(
                        "(await chrome.storage.session.get('selected')).selected.snapshot.id"
                    )
                    retrieval = await api_json(
                        backend,
                        token,
                        "POST",
                        "/research/retrieve",
                        {"snapshot_id": snapshot_id, "top_k": 3, "mode": "hybrid"},
                    )
                    rendered = await panel.evaluate(
                        "Array.from(document.querySelectorAll('#research-results > div'))"
                        ".map(block => ({text: block.textContent, "
                        "quote: block.querySelector('blockquote')?.textContent || ''}))"
                    )
                    return snapshot_id, retrieval, rendered

                def rank(retrieval, url):
                    for index, row in enumerate(retrieval["results"], start=1):
                        if row["source_url"] == url:
                            return index, row
                    return None, None

                async def explain(target_url):
                    clicked = await panel.evaluate(
                        "(() => { const target = "
                        + json.dumps(target_url)
                        + "; const block = Array.from("
                        "document.querySelectorAll('#research-results > div'))"
                        ".find(row => row.textContent.includes(target));"
                        "if (!block) return false;"
                        "const button = Array.from(block.querySelectorAll('button'))"
                        ".find(row => row.textContent === 'Explain connection to this page');"
                        "if (!button) return false; button.click(); return true; })()"
                    )
                    assert clicked, "connection action missing for " + target_url
                    await panel.wait(
                        "document.querySelector('#connection').textContent"
                        ".includes('Historical source quote:')"
                    )
                    text = await panel.evaluate("document.querySelector('#connection').textContent")
                    return text, latest_connection(work / "demo.db")

                chapters = {}
                for chapter in ("alive-12-status", "alive-11-corrections", "alive-14-status"):
                    chapters[chapter] = await remember(chapter)
                    await save_panel_png(panel, "0" + str(len(chapters)) + "-" + chapter)

                captured = await authorise("alive-12-status")
                assert all(word not in captured for word in CHROME_STRINGS), captured[:500]
                assert "Retrieval advantage: NOT DEMONSTRATED." in captured
                report["capture"] = {
                    "chapter": "alive-12-status",
                    "chars": len(captured),
                    "chrome_excluded": True,
                    "sha256_matches_memory": hashlib.sha256(captured.encode()).hexdigest()
                    == chapters["alive-12-status"]["data"]["sha256"],
                }

                # R1: the earlier chapter must be retrieved and the connection must be lexical only.
                _, retrieval, _ = await find("alive-13-what-was-wrong")
                r1_rank, r1 = rank(retrieval, URLS["alive-12-status"])
                assert r1_rank == 1, r1_rank
                assert r1["sha256"] == chapters["alive-12-status"]["data"]["sha256"]
                assert r1["excerpt"] in captured
                r1_text, r1_connection = await explain(URLS["alive-12-status"])
                assert r1_connection["relation_type"] == "topic_overlap_candidate"
                assert "same_concept" in r1_connection["shared_terms"]
                assert "supersed" not in r1_connection["explanation"].lower()
                report["r1"] = {
                    "rank": r1_rank,
                    "memory_id": r1["memory_id"],
                    "source_url": r1["source_url"],
                    "sha256": r1["sha256"],
                    "relation_type": r1_connection["relation_type"],
                    "shared_terms": r1_connection["shared_terms"],
                    "current_quote": r1_connection["current_quote"],
                    "historical_quote": r1_connection["historical_quote"],
                    "quote_validation": r1_connection["quote_validation"],
                    "explanation": r1_connection["explanation"],
                    "ui_quote_visible": "Historical source quote:" in r1_text,
                }
                await save_panel_png(panel, "04-r1-connection")

                # R2: the ALIVE-12 predecessor must be retrieved but not ranked first.
                _, retrieval, rendered = await find("alive-13-status")
                r2_rank, r2 = rank(retrieval, URLS["alive-12-status"])
                assert r2_rank is not None and r2_rank != 1, r2_rank
                report["r2"] = {
                    "rank": r2_rank,
                    "top": [
                        {"rank": index, "source_url": row["source_url"]}
                        for index, row in enumerate(retrieval["results"], start=1)
                    ],
                    "sha256": r2["sha256"],
                    "ui_visible": any("ALIVE-12" in row["text"] for row in rendered),
                }
                await save_panel_png(panel, "05-r2-ranking")

                # R3: a lexical candidate must not be presented as support.
                _, retrieval, _ = await find("alive-14-status")
                r3_rank, r3 = rank(retrieval, URLS["alive-11-corrections"])
                assert r3_rank is not None
                r3_text, r3_connection = await explain(URLS["alive-11-corrections"])
                assert r3_connection["relation_type"] == "topic_overlap_candidate"
                assert {"paid", "calls"} <= set(r3_connection["shared_terms"])
                assert "does not establish" in r3_connection["explanation"]
                report["r3"] = {
                    "rank": r3_rank,
                    "memory_id": r3["memory_id"],
                    "relation_type": r3_connection["relation_type"],
                    "shared_terms": r3_connection["shared_terms"],
                    "explanation": r3_connection["explanation"],
                    "strict_abstention_test": "xfail(strict) remains in tests/test_notebook_01.py",
                }
                await save_panel_png(panel, "06-r3-connection")

                # Withdrawal: the R1 target disappears from subsequent retrieval.
                clicked = await panel.evaluate(
                    "(() => { const target = "
                    + json.dumps(URLS["alive-12-status"])
                    + "; const block = Array.from("
                    "document.querySelectorAll('#research-results > div'))"
                    ".find(row => row.textContent.includes(target));"
                    "if (!block) return false;"
                    "const button = Array.from(block.querySelectorAll('button'))"
                    ".find(row => row.textContent === 'Withdraw this memory');"
                    "if (!button) return false; button.click(); return true; })()"
                )
                assert clicked
                await panel.wait(
                    "document.querySelector('#research-status').textContent"
                    ".includes('Withdrew displayed memory')"
                )
                _, retrieval, _ = await find("alive-14-status")
                assert rank(retrieval, URLS["alive-12-status"])[0] is None
                report["withdrawal"] = {
                    "withdrawn": URLS["alive-12-status"],
                    "retrieved_after_withdrawal": False,
                }
                await save_panel_png(panel, "07-withdrawn")

                # Restart: withdrawn memory stays gone; remaining memories persist.
                chrome_harness.stop_backend(process, log)
                process, log = chrome_harness.start_backend(work, env, port)
                await chrome_harness.wait_backend(backend)
                await panel.send("Page.reload")
                await panel.wait(
                    "document.querySelector('#connect')"
                    " && !document.querySelector('#connect').disabled"
                )
                await chrome_harness.connect_panel(panel, backend)
                _, retrieval, _ = await find("alive-14-status")
                assert rank(retrieval, URLS["alive-12-status"])[0] is None
                assert rank(retrieval, URLS["alive-11-corrections"])[0] is not None
                report["restart"] = {
                    "withdrawn_still_absent": True,
                    "other_memory_present": True,
                }
                await save_panel_png(panel, "08-restart")

                # Revocation: stop the observation and prove a further send is refused.
                grant_id = await panel.evaluate(
                    "(await chrome.storage.session.get('grantId')).grantId"
                )
                await panel.click("#stop")
                await panel.wait(
                    "document.querySelector('#status').textContent.includes('Stopped')"
                )
                state = await panel.evaluate(
                    "(await chrome.storage.session.get(['grantId','latest','selected']))"
                )
                assert not state.get("grantId") and not state.get("latest")
                assert grant_status(work / "demo.db", grant_id) == "revoked"
                await panel.click("#live-review")
                await panel.wait(
                    "document.querySelector('#live-error').textContent"
                    ".includes('Authorise the current page')"
                )
                report["revocation"] = {
                    "grant_status": grant_status(work / "demo.db", grant_id),
                    "session_cleared": True,
                    "further_review_refused": True,
                }
                await save_panel_png(panel, "09-revoked")
                with sqlite3.connect(work / "demo.db") as database:
                    counts = {
                        kind: database.execute(
                            "select count(*) from web_experiences where kind=?", (kind,)
                        ).fetchone()[0]
                        for kind in (
                            "note",
                            "research_memory",
                            "research_connection",
                            "research_relationship_analysis",
                        )
                    }
                    statuses = dict(
                        database.execute(
                            "select status, count(*) from web_experiences "
                            "where kind='research_memory' group by status"
                        ).fetchall()
                    )
                assert counts["note"] == 0
                assert counts["research_relationship_analysis"] == 0
                report["database"] = {"counts": counts, "memory_statuses": statuses}
                report["status"] = "PASS"
            finally:
                await context.close()
    except BaseException as error:
        report["status"] = "FAIL"
        report["error"] = type(error).__name__ + ": " + str(error)
        raise
    finally:
        chrome_harness.stop_backend(process, log)
        if hugo.poll() is None:
            hugo.terminate()
            try:
                hugo.wait(timeout=10)
            except subprocess.TimeoutExpired:
                hugo.kill()
        hugo_log.close()
        (EVIDENCE / "result.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        print(json.dumps(report, indent=2))


if __name__ == "__main__":
    asyncio.run(main())
