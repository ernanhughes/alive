// ALIVE Notebook: the companion's real visible-text capture over the built Hugo pages,
// and the exact-URL allowlist in extension/config.js.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { test } = require('node:test');
const { JSDOM } = require('../dashboard/node_modules/jsdom');
const { capture } = require('../extension/capture.js');

const root = path.join(__dirname, '..');
const spec = JSON.parse(fs.readFileSync(path.join(root, 'site/notebook/chapters.json'), 'utf8'));
const relations = JSON.parse(fs.readFileSync(path.join(root, 'site/notebook/relations.json'), 'utf8')).relations;
const squash = s => s.replace(/\s+/g, ' ').trim();
const plain = s => squash(s.replace(/\[([^\]]+)\]\([^)]*\)/g, '$1').replace(/`/g, '').replace(/\*\*/g, ''));

test('config.js authorises exactly the notebook chapter URLs on loopback port 1313', () => {
  const source = fs.readFileSync(path.join(root, 'extension/config.js'), 'utf8')
    .replace(/^export /gm, '') + '\nreturn AUTHORISED_PAGES;';
  const pages = new Function(source)().filter(page => page.includes(':1313/'));
  const expected = ['127.0.0.1', 'localhost'].flatMap(host =>
    spec.chapters.map(c => `http://${host}:${spec.port}/chapters/${c.id}/`));
  assert.deepEqual([...pages].sort(), expected.sort());
  const manifest = fs.readFileSync(path.join(root, 'extension/manifest.json'), 'utf8');
  assert.ok(!manifest.includes('1313'), 'manifest permissions must not be widened for the notebook');
});

const hugo = spawnSync('hugo', ['version']);
test('capture of built chapters excludes navigation, contents and footer', () => {
  assert.equal(hugo.status, 0, 'Hugo must be installed for notebook capture validation');
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'alive-notebook-'));
  try {
    const built = spawnSync('hugo', ['--source', path.join(root, 'site'), '--destination', out, '--quiet']);
    assert.equal(built.status, 0, String(built.stderr));
    for (const chapter of spec.chapters) {
      const html = fs.readFileSync(path.join(out, 'chapters', chapter.id, 'index.html'), 'utf8');
      const dom = new JSDOM(html);
      dom.window.Element.prototype.getClientRects = () => [{}];
      const document = dom.window.document;
      // The same root selection as extension/observer.js.
      const content = document.querySelector('main,article,[role="main"]');
      assert.equal(content.tagName, 'MAIN', chapter.id);
      const text = capture(content).text;
      for (const chrome of ['The ALIVE Notebook', 'Chapters', 'Source SHA-256', 'Generated by', 'Parts reproduced']) {
        assert.ok(!text.includes(chrome), `${chapter.id} captured page chrome: ${chrome}`);
      }
      assert.ok(Array.from(text).length <= spec.capture_window, `${chapter.id} exceeds the saved excerpt`);
      const shown = squash(text);
      for (const relation of relations.filter(r => r.authenticity === 'real')) {
        for (const side of ['older', 'newer']) {
          if (relation[side].chapter !== chapter.id) continue;
          for (const quote of relation[side].quotes) {
            assert.ok(shown.includes(plain(quote)), `${relation.id}: ${side} quote missing from captured ${chapter.id}`);
          }
        }
      }
    }
  } finally {
    fs.rmSync(out, { recursive: true, force: true });
  }
});
